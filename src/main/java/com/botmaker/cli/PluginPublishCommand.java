package com.botmaker.cli;

import com.botmaker.cli.catalog.ApprovedRelease;
import com.botmaker.cli.catalog.Entry;
import com.botmaker.cli.catalog.EntryPath;
import com.botmaker.cli.catalog.GitHubFacts;
import com.botmaker.cli.catalog.PluginEntry;
import com.botmaker.cli.project.Poms;
import com.botmaker.cli.project.Tags;
import com.botmaker.cli.validate.CheckResult;
import com.botmaker.cli.validate.PluginSubject;
import com.botmaker.cli.validate.PluginValidator;
import com.botmaker.plugin.api.StudioPlugin;
import com.botmaker.plugin.host.PluginLoader;
import picocli.CommandLine.Command;
import picocli.CommandLine.Option;
import picocli.CommandLine.ParentCommand;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.concurrent.Callable;

/**
 * {@code botmaker plugin publish} — validate, then compose the catalog entry and open the pull request.
 *
 * <p><b>The author never hand-edits anything in the catalog.</b> The entry is {@code {id, repo, tag}}
 * (2026-10-23): the id is the plugin's own, read from the jar, and everything else Studio shows — the name, the
 * contract version, the editor dependencies, the description — the catalog derives from the pom and the
 * repository at that tag. A human retyping those is a human introducing a typo into the file that is the
 * catalog's primary key.
 *
 * <p>Validation runs first and a failure stops it. That is the whole point of {@code validate} being a
 * library rather than a command: the check that refuses the pull request is the check that refused to open
 * it.
 *
 * <p><b>Nothing is published that nobody has followed.</b> The version is a <b>git tag</b> rather than the
 * pom's {@code <version>} (see {@link #publishedVersion}), a {@code -SNAPSHOT} is refused by name, the
 * coordinate is resolved, and the catalog's rules 2–5 (the repository, a published GitHub Release at the tag,
 * made by the signed-in user) run before the pull request is opened.
 *
 * <p><b>One file, {@code plugins/&lt;plugin-id&gt;.json}.</b> Two authors publishing on the same day are two
 * pull requests with no line in common; {@code catalog.json} is generated by the catalog's own CI.
 */
@Command(name = "publish",
        header = "Validate, then open the catalog pull request.",
        description = "The entry is the plugin's id, its repository and the tag; the catalog derives the rest. "
                + "Its checks merge the pull request when they pass.",
        mixinStandardHelpOptions = true)
final class PluginPublishCommand implements Callable<Integer> {

    @ParentCommand
    private PluginCommand parent;

    @Option(names = "--dir", defaultValue = ".",
            description = "The plugin project. Default: ${DEFAULT-VALUE}")
    private String directory;

    @Option(names = "--repo", paramLabel = "<owner/name>",
            description = "Where the plugin's source lives. Required for a real run; without it this is a "
                    + "dry run, because an entry needs somewhere for a reader to go and look.")
    private String repo;

    /**
     * <b>{@code --tag}, not {@code --version}, and the name is forced rather than chosen.</b>
     * {@code mixinStandardHelpOptions} already declares {@code -V, --version} on every command here, so a
     * second one would be a duplicate picocli refuses at construction. It reads better anyway: what JitPack
     * serves an artifact under is a git tag.
     */
    @Option(names = "--tag", paramLabel = "<tag>",
            description = "The published version the catalog's check will resolve. Default: the newest git "
                    + "tag on this working copy, or the pom's own <version> when there is not one.")
    private String tag;

    @Option(names = "--dry-run", description = "Print the entry and open nothing.")
    private boolean dryRun;

    @Option(names = "--no-build", description = "Trust the existing target/classes.")
    private boolean noBuild;

    @Override
    public Integer call() throws IOException {
        Console console = parent.main().console();
        Path dir = Path.of(directory).toAbsolutePath().normalize();
        Path pom = dir.resolve("pom.xml");
        if (!Files.isRegularFile(pom)) {
            throw new IOException(
                    "no pom.xml in " + dir + " — point `botmaker plugin publish` at a plugin project");
        }

        // Before the compile: a refusal the author waits a minute for reads as a fault in the tool.
        String published = publishedVersion(dir, pom);
        String snapshot = snapshotRefusal(published);
        if (snapshot != null) {
            console.error(snapshot);
            return 1;
        }
        Optional<String> author = Optional.empty();
        if (repo != null && !dryRun) {
            author = CatalogPr.login();
            if (author.isEmpty()) {
                console.error("`gh` is not signed in; run `gh auth login` first.");
                return 1;
            }
        }

        PluginSubject subject = parent.main().subjects().fromDirectory(dir, !noBuild);

        // Aside, on stderr: this command's stdout is the entry, and `--dry-run > entry.json` has to be a
        // file a parser will read.
        List<CheckResult> results = PluginValidator.validate(subject);
        console.reportAside(results);
        if (!PluginValidator.passed(results)) {
            console.error("not publishing: the plugin does not pass its own checks, and the catalog runs"
                    + " these same checks on the pull request");
            return 1;
        }

        Poms.Dependency self = Poms.coordinate(subject.pom());
        String coordinate = self.groupId() + ":" + self.artifactId() + ":" + published;
        String id = pluginId(subject);

        if (dryRun || repo == null) {
            if (repo == null) {
                console.warn("--repo <owner/name> was not given, so this is a dry run: the catalog entry"
                        + " needs somewhere for a reader to go and look at the source.");
            }
            console.out("would list " + id + " " + (repo == null ? "owner/name" : repo) + " " + published);
            return 0;
        }
        if (!resolves(coordinate)) {
            return 1;
        }
        Optional<EntryPath> path = EntryPath.parse(EntryPath.PLUGINS + id + ".json");
        if (path.isEmpty()) {
            console.error("the plugin's id " + id + " cannot name a catalog file: letters, digits, '.', '-'"
                    + " and '_', at most 128.");
            return 1;
        }
        GitHubFacts facts = GitHubFacts.anonymousOrToken();
        Optional<ApprovedRelease> release = ApprovedRelease.pinPlugin(facts, repo, published);
        if (release.isEmpty()) {
            console.error("could not pin " + repo + " " + published + ": GitHub shows no such tag, or JitPack"
                    + " serves no jar or pom for it yet. Re-run once it does.");
            return 1;
        }
        Optional<Entry> previous = CatalogPr.listed(facts, path.get());
        if (previous.flatMap(e -> e.release(published)).isPresent()) {
            console.step(id + " " + published + " is already listed in the catalog.");
            return 0;
        }
        Entry entry = previous.map(e -> e.appended(release.get()))
                .orElse(new PluginEntry(id, repo, List.of(release.get())));
        if (!CatalogPr.passes(console, entry, author.orElseThrow(), previous, facts)) {
            console.error("the catalog would refuse the entry; no pull request opened.");
            return 1;
        }
        return CatalogPr.open(console, CatalogPr.Change.put(entry, "botmaker plugin publish"), author.get());
    }

    /**
     * The version the entry publishes, which is the version the catalog's check resolves from JitPack.
     *
     * <p><b>The newest git tag, not the pom's {@code <version>}, and that is a correction rather than a
     * preference.</b> JitPack builds a tag on demand and serves the result under that tag whatever the pom
     * says — this project's own poms carried a cosmetic {@code 0.0.0-SNAPSHOT} until 2026-10-06 — so a
     * pom version resolves only where it happens to equal the tag. {@code --tag} overrides both, for the
     * author whose newest tag is not what they publish under.
     */
    private String publishedVersion(Path dir, Path pom) throws IOException {
        if (tag != null && !tag.isBlank()) {
            return tag.trim();
        }
        Optional<String> tag = Tags.newest(dir);
        if (tag.isPresent()) {
            return tag.get();
        }
        return Poms.coordinate(pom).version();
    }

    /**
     * A snapshot is refused here rather than left to the catalog, because the point is that the author sees it.
     *
     * <p>{@code botmaker plugin new} generates {@code 0.1.0-SNAPSHOT}, so publishing straight after generating is
     * the very first thing a new author does and produced an entry whose check failed in the <em>registry's</em>
     * CI. Returns the refusal, or {@code null} when there is nothing to refuse.
     */
    static String snapshotRefusal(String published) {
        if (published == null || published.isBlank()) {
            return "no version to publish: this working copy has no git tag and its pom declares no"
                    + " <version>. Tag a release, or pass --tag <tag>.";
        }
        if (published.endsWith("-SNAPSHOT")) {
            return "the version to publish is " + published + ", and JitPack cannot resolve a snapshot:"
                    + " the catalog's check would download nothing. Tag a release (`git tag v0.1.0 && git"
                    + " push --tags`) and re-run, or pass --tag <tag>.";
        }
        return null;
    }

    /**
     * The check's own download, run locally: a coordinate that will not resolve here is a pull request that
     * cannot pass, and finding that out costs seconds where finding it out in CI costs a round trip.
     */
    private boolean resolves(String coordinate) {
        Console console = parent.main().console();
        try {
            parent.main().subjects().fromCoordinate(coordinate, Set.of());
            return true;
        } catch (IOException e) {
            console.error("nobody can download " + coordinate + " yet, so the catalog's check could not"
                    + " check it either:\n" + e.getMessage()
                    + "\nPush the tag and let JitPack build it, then re-run.");
            return false;
        }
    }

    /** The plugin's own id, which names its entry. Everything else but the repository and the release is derived. */
    private String pluginId(PluginSubject subject) {
        Console console = parent.main().console();
        String id;
        try (PluginLoader loaded =
                     PluginLoader.open(subject.classpath().stream().map(Object::toString).toList())) {
            // The validator has already refused an empty load, so there is at least one plugin here. The
            // FIRST is the entry's subject: a jar contributing two is legal and rare, and picking silently
            // would be worse than the warning.
            List<StudioPlugin> plugins = loaded == null ? List.of() : loaded.plugins();
            if (plugins.size() > 1) {
                console.warn("this jar contributes " + plugins.size() + " plugins; the entry describes"
                        + " the first, " + plugins.getFirst().id());
            }
            StudioPlugin plugin = plugins.getFirst();
            id = plugin.id();
        }
        return id;
    }
}
